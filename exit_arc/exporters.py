# Markdown
# --------------------------------------------------------------------------

def _md_text(s):
    out = str(s or "")
    for ch in "\\`*_[]<>#|":
        out = out.replace(ch, "\\" + ch)
    return out


def _md_url(url):
    if any(c in url for c in " ()<>"):
        return "<" + url.replace("<", "%3C").replace(">", "%3E") + ">"
    return url


def _md_nodes(nodes, depth=0):
    pad = "  " * depth
    out = []
    for n in nodes:
        if n["type"] == "link":
            out.append(f'{pad}- [{_md_text(n["title"] or n["url"])}]({_md_url(n["url"])})')
        else:
            out.append(f'{pad}- **{_md_text(n["title"])}**' + ("" if n["children"] else " (empty folder)"))
            out += _md_nodes(n["children"], depth + 1)
    return out


EXT_COLUMNS = ("Firefox", "Zen", "Chrome")


def _ext_cell(ext, target):
    m = (ext.get("availability") or {}).get(target.lower())
    if m is None:
        return "not checked"
    if m.get("status") == "match":
        return f'yes ([{_md_text(m["name"])}]({m["url"]}))' if m.get("url") else "yes"
    if m.get("status") == "possible":
        return f'maybe: [{_md_text(m["name"])}]({m["url"]})'
    if m.get("status") == "unknown":
        return "not checked" + (f' ({_md_text(m["note"])})' if m.get("note") else "")
    return "no" + (f' ({_md_text(m["note"])})' if m.get("note") else "")


def build_markdown(export):
    lines = ["# My Arc sidebar", "", f'Exported {export.get("exportedAt", "")} by {export.get("tool", "exit-arc")}.', ""]
    multi = len(export["profiles"]) > 1
    h = "##" if not multi else "###"
    for p in export["profiles"]:
        if multi:
            lines += [f'## Profile: {_md_text(p["name"])}', ""]
        lines += [f"{h} Favourites", ""]
        lines += (_md_nodes(p["favourites"]) or ["_None_"]) + [""]
        for s in p["spaces"]:
            lines += [f"{h} {_md_text(space_label(s))}", ""]
            lines += (_md_nodes(s["pinned"]) or ["_No pinned tabs_"]) + [""]
            if s["unpinned"]:
                lines += [f"{h}# Open tabs (unpinned)", ""] + _md_nodes(s["unpinned"]) + [""]
        exts = p.get("extensions")
        if exts is not None:
            lines += [f"{h} Extensions", ""]
            if not exts:
                lines += ["_None_", ""]
            else:
                lines.append("| Extension | " + " | ".join(EXT_COLUMNS) + " |")
                lines.append("| --- |" + " --- |" * len(EXT_COLUMNS))
                for e in exts:
                    label = _md_text(e["name"]) + ("" if e["enabled"] else " (disabled)") + \
                        (" (came with Arc)" if e["preinstalled"] else "")
                    lines.append(f"| {label} | " + " | ".join(_ext_cell(e, t) for t in EXT_COLUMNS) + " |")
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render(export, fmt, layout="toolbar", include_unpinned=False):
    if fmt == "json":
        return build_json(export)
    if fmt == "html":
        return build_html(export, layout, include_unpinned)
    if fmt == "csv":
        return build_csv(export)
    if fmt == "md":
        return build_markdown(export)
    raise ToolError(f"Unknown format {fmt!r}")


def parse_formats(value):
    fmts = [f.strip().lower() for f in (value or "").split(",") if f.strip()]
    fmts = ["md" if f == "markdown" else f for f in fmts]
    bad = [f for f in fmts if f not in FORMATS]
    if bad or not fmts:
        raise ToolError(f"--format takes a comma-separated list of: {', '.join(FORMATS)}")
    return list(dict.fromkeys(fmts))
